//! `pve-meta-rs`: the `PVE::RS::Meta` Perl bindings, exposing
//! [`pve_meta_core::store::MetaStore`]'s guest lifecycle operations
//! (snapshot/rollback/delsnap/clone/destroy, backup export/import) to PVE's
//! Perl code via `perlmod`.
//!
//! Built as a `cdylib` (`libpve_meta_rs.so`); the `.pm` glue files
//! (`PVE/RS/Meta.pm`, `Proxmox/Lib/PVEMeta.pm`) are generated separately by
//! `genpackage.pl` (see `Makefile`), not by this crate.
//!
//! The store root defaults to `/etc/pve/meta` and can be overridden with the
//! `PVE_META_ROOT` environment variable (used by tests and by
//! `test/basic.pl`).

use std::path::PathBuf;

use pve_meta_core::error::Error as CoreError;
use pve_meta_core::format::Format;
use pve_meta_core::store::{MetaStore, RollbackOutcome};

mod api;

/// Opens a fresh [`MetaStore`] rooted at `$PVE_META_ROOT`, or
/// `/etc/pve/meta` if unset. Cheap: `MetaStore::new` does no I/O.
fn open_store() -> MetaStore {
    let root = std::env::var_os("PVE_META_ROOT")
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from("/etc/pve/meta"));
    MetaStore::new(root)
}

/// Splits an `export_for_backup` blob into its `#pve-meta-format: <ext>`
/// header and the raw document text that follows it.
fn split_backup_header(data: &str) -> anyhow::Result<(Format, &str)> {
    let (header, rest) = data
        .split_once('\n')
        .ok_or_else(|| anyhow::anyhow!("missing '#pve-meta-format: <ext>' header"))?;
    let ext = header
        .strip_prefix("#pve-meta-format: ")
        .ok_or_else(|| anyhow::anyhow!("malformed pve-meta backup header: {header:?}"))?;
    let format = Format::from_ext(ext)
        .ok_or_else(|| anyhow::anyhow!("unknown pve-meta backup format '{ext}'"))?;
    Ok((format, rest))
}

/// The `Proxmox::Lib::PVEMeta` library-loader package generated by
/// `genpackage.pl` (`--lib-package=Proxmox::Lib::PVEMeta`, see `Makefile`)
/// bootstraps itself on `use` (its own generated `BEGIN` block), so this crate
/// must export a matching `boot_Proxmox__Lib__PVEMeta` symbol even though it
/// has no functions of its own to export -- mirrors upstream `pve-rs`'s
/// `Proxmox::Lib::PVE` package (`proxmox-perl-rs/pve-rs/src/bindings/mod.rs`).
#[perlmod::package(name = "Proxmox::Lib::PVEMeta", lib = "pve_meta_rs")]
mod proxmox_lib_pve_meta {}

#[perlmod::package(name = "PVE::RS::Meta", lib = "pve_meta_rs")]
mod pve_rs_meta {
    //! The `PVE::RS::Meta` package: guest metadata lifecycle hooks, called
    //! from PVE's guest lifecycle code (snapshot/rollback/clone/destroy) and
    //! from vzdump backup/restore.

    use anyhow::Error;

    use pve_meta_core::store::DocId;

    use super::{open_store, split_backup_header, RollbackOutcome};

    /// Copies `$vmid`'s current document to its `$snapname` snapshot file.
    /// A no-op if the guest has no document.
    ///
    /// Returns `1` if a copy was made, `0` otherwise.
    #[export]
    pub fn on_snapshot(vmid: u32, snapname: &str) -> Result<bool, Error> {
        Ok(open_store().snapshot(vmid, snapname)?)
    }

    /// Restores `$vmid`'s `$snapname` snapshot copy over its current
    /// document. If no snapshot copy exists but a current document does, the
    /// current document is removed (the guest had no metadata when the
    /// snapshot was taken).
    ///
    /// Returns `"restored"`, `"removed"`, or `"none"`.
    #[export]
    pub fn on_rollback(vmid: u32, snapname: &str) -> Result<String, Error> {
        let outcome = open_store().rollback(vmid, snapname)?;
        Ok(match outcome {
            RollbackOutcome::Restored => "restored",
            RollbackOutcome::RemovedNoSnapshot => "removed",
            RollbackOutcome::NoOp => "none",
        }
        .to_string())
    }

    /// Removes `$vmid`'s `$snapname` snapshot copy. Idempotent.
    ///
    /// Returns `1` if a copy existed and was removed, `0` otherwise.
    #[export]
    pub fn on_delsnap(vmid: u32, snapname: &str) -> Result<bool, Error> {
        let store = open_store();
        let existed = store.list_snapshots(vmid)?.iter().any(|n| n == snapname);
        store.delete_snapshot(vmid, snapname)?;
        Ok(existed)
    }

    /// Copies `$vmid`'s current document (not its snapshots) to `$newid`,
    /// *overwriting* any document `$newid` already has -- mirroring
    /// `PVE::Firewall::Helpers::clone_vmfw_conf`'s unlink-then-copy, soft-fail
    /// clone (a stale target document left over from an earlier destroy race
    /// must not block a clone).
    ///
    /// A no-op if `$vmid` has no document; in that case any stale document
    /// `$newid` already has is still removed, so the (failed) clone leaves
    /// `$newid` clean.
    ///
    /// Returns `1` if a copy was made, `0` otherwise.
    #[export]
    pub fn on_clone(vmid: u32, newid: u32) -> Result<bool, Error> {
        let store = open_store();
        let src = match store.read(DocId::Guest(vmid)) {
            Ok(doc) => doc,
            Err(super::CoreError::NotFound(_)) => {
                if let Some(stale) = store.locate(DocId::Guest(newid))? {
                    std::fs::remove_file(&stale.path)?;
                }
                return Ok(false);
            }
            Err(e) => return Err(e.into()),
        };
        // `put_raw` with no expected digest always creates-or-overwrites (and
        // switches the target's extension to match the source's format if it
        // previously differed), so this never dies on an existing `$newid`
        // document the way `MetaStore::clone` would.
        store.put_raw(DocId::Guest(newid), &src.raw, Some(src.format), None)?;
        Ok(true)
    }

    /// Removes `$vmid`'s document and all of its snapshot copies. Idempotent.
    ///
    /// Returns the number of files removed.
    #[export]
    pub fn on_destroy(vmid: u32) -> Result<u32, Error> {
        let store = open_store();
        let snapshots = store.list_snapshots(vmid)?;
        let had_document = store.locate(DocId::Guest(vmid))?.is_some();
        if had_document {
            // Removes the document and every snapshot copy in one go.
            store.destroy(vmid)?;
        } else {
            // No live document: still clean up any orphaned snapshot files.
            for name in &snapshots {
                store.delete_snapshot(vmid, name)?;
            }
        }
        Ok(snapshots.len() as u32 + u32::from(had_document))
    }

    /// Returns `undef` if `$vmid` has no document, else a string
    /// `"#pve-meta-format: <ext>\n"` followed by the document's raw text.
    /// The header records the format so `import_from_backup` can restore it
    /// without re-guessing; it is stripped on import (and would otherwise
    /// just be a harmless comment line in all three supported formats).
    #[export]
    pub fn export_for_backup(vmid: u32) -> Result<Option<String>, Error> {
        match open_store().read(DocId::Guest(vmid)) {
            Ok(doc) => Ok(Some(format!(
                "#pve-meta-format: {}\n{}",
                doc.format.ext(),
                doc.raw
            ))),
            Err(super::CoreError::NotFound(_)) => Ok(None),
            Err(e) => Err(e.into()),
        }
    }

    /// Parses the `"#pve-meta-format: <ext>\n..."` blob produced by
    /// `export_for_backup` and writes it as `$vmid`'s document, replacing any
    /// existing document for that vmid. The content is validated through the
    /// core parser/lint before being written; dies on invalid content.
    ///
    /// Always returns `1`.
    #[export]
    pub fn import_from_backup(vmid: u32, data: &str) -> Result<bool, Error> {
        let (format, text) = split_backup_header(data)?;
        open_store().put_raw(DocId::Guest(vmid), text, Some(format), None)?;
        Ok(true)
    }

    /// Returns an array ref of `$vmid`'s snapshot names.
    #[export]
    pub fn list_snapshots(vmid: u32) -> Result<Vec<String>, Error> {
        Ok(open_store().list_snapshots(vmid)?)
    }

    /// Returns `1` if `$vmid` has a document, `0` otherwise.
    #[export]
    pub fn has_document(vmid: u32) -> Result<bool, Error> {
        Ok(open_store().locate(DocId::Guest(vmid))?.is_some())
    }

    /// Returns this crate's version string (for the health endpoint /
    /// `pve-meta health`).
    #[export]
    pub fn version() -> String {
        env!("CARGO_PKG_VERSION").to_string()
    }

    // -- API-shaped exports (`PVE::API2::Meta`, `docs/NATIVE-API-SPEC.md`) --
    //
    // Thin wrappers over `super::api` (see that module's docs for the wire
    // contract). All of these die with a Rust `anyhow::Error` whose
    // `Display` is `"NNN: message"` (an HTTP status prefix); the Perl layer
    // parses that prefix and re-raises via `PVE::Exception::raise`.

    /// `GET /meta/version` -> `{ token, changed }`.
    #[export]
    pub fn api_version() -> Result<super::api::ApiVersion, Error> {
        super::api::version()
    }

    /// `GET /meta/health` -> `{ store: {root, files, bytes}, version, hooks: {} }`.
    #[export]
    pub fn api_health() -> Result<super::api::ApiHealth, Error> {
        super::api::health()
    }

    /// `GET /meta/inventory` -> guests from `.vmlist`, enriched with their
    /// display name.
    #[export]
    pub fn api_inventory() -> Result<Vec<super::api::InventoryEntry>, Error> {
        super::api::inventory()
    }

    /// `GET /meta/guests` -> guest documents, optionally filtered by `has`
    /// (a dotted path that must be present).
    #[export]
    pub fn api_list_guests(has: Option<&str>) -> Result<Vec<super::api::GuestListEntry>, Error> {
        super::api::list_guests(has)
    }

    /// `GET /meta/guests/{vmid}` / `GET /meta/datacenter` (`$id` is a vmid
    /// or `"datacenter"`).
    #[export]
    pub fn api_get(id: &str, comments: bool, raw: bool) -> Result<super::api::ApiDocument, Error> {
        super::api::get_document(id, comments, raw)
    }

    /// `GET .../subtree?path=...` -> `{ data_json, digest }`. 404s if
    /// nothing exists at `path`.
    #[export]
    pub fn api_subtree(id: &str, path: &str) -> Result<super::api::ApiSubtree, Error> {
        super::api::get_subtree(id, path)
    }

    /// `PUT /meta/guests/{vmid}` / `PUT /meta/datacenter`: merge-patch.
    /// `patch_json` is a JSON-encoded string (avoids Perl number/string
    /// ambiguity); creates the document if it does not exist.
    #[export]
    pub fn api_patch(id: &str, patch_json: &str, digest: Option<&str>, dry_run: bool) -> Result<super::api::ApiDocument, Error> {
        super::api::patch_document(id, patch_json, digest, dry_run)
    }

    /// `PUT .../raw`: full-text replace.
    #[export]
    pub fn api_put_raw(
        id: &str,
        content: &str,
        format: Option<&str>,
        digest: Option<&str>,
        dry_run: bool,
    ) -> Result<super::api::ApiDocument, Error> {
        super::api::put_raw_document(id, content, format, digest, dry_run)
    }

    /// `POST .../convert`: re-dumps the document in another format.
    #[export]
    pub fn api_convert(id: &str, format: &str, digest: Option<&str>) -> Result<super::api::ApiDocument, Error> {
        super::api::convert_document(id, format, digest)
    }

    /// `DELETE /meta/guests/{vmid}` / `DELETE /meta/datacenter`.
    #[export]
    pub fn api_delete(id: &str) -> Result<bool, Error> {
        super::api::delete_document(id)
    }

    /// `GET /meta/guests/{vmid}/snapshots` -> snapshot names.
    #[export]
    pub fn api_snapshots(vmid: u32) -> Result<Vec<String>, Error> {
        super::api::list_guest_snapshots(vmid)
    }

    /// `POST /meta/guests/{vmid}/snapshot` -> `{ created }`.
    #[export]
    pub fn api_snapshot(vmid: u32, name: &str) -> Result<super::api::ApiCreated, Error> {
        super::api::snapshot_guest(vmid, name)
    }

    /// `POST /meta/guests/{vmid}/rollback` -> `{ outcome }`.
    #[export]
    pub fn api_rollback(vmid: u32, name: &str) -> Result<super::api::ApiOutcome, Error> {
        super::api::rollback_guest(vmid, name)
    }

    /// `DELETE /meta/guests/{vmid}/snapshots/{name}`.
    #[export]
    pub fn api_delete_snapshot(vmid: u32, name: &str) -> Result<bool, Error> {
        super::api::delete_guest_snapshot(vmid, name)
    }

    /// `POST /meta/guests/{vmid}/clone` -> the new guest's document.
    #[export]
    pub fn api_clone(vmid: u32, newid: u32) -> Result<super::api::ApiDocument, Error> {
        super::api::clone_document(vmid, newid)
    }

    /// `GET /meta/registry` -> a view of `datacenter.operators`.
    #[export]
    pub fn api_registry() -> Result<Vec<super::api::ApiRegistryEntry>, Error> {
        super::api::registry()
    }

    /// `GET /meta/schemas/{vmid}` -> the JSON schemas applicable to a
    /// guest's document, as a JSON object string keyed by namespace prefix.
    #[export]
    pub fn api_schemas(vmid: u32) -> Result<String, Error> {
        super::api::schemas_for_guest(vmid)
    }
}
